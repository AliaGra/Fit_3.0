/**
 * Коротке пояснення: навіщо заміри, цілі, акцент і активність.
 * Показується кнопкою «💡 Навіщо заміри і цілі» (окремий екран у боті, не файл).
 * Тренер (для себе): лише в «Мої показники тіла». Не в «Оновити заміри» / «Бажані параметри».
 */
const { CONSTANTS } = require('./constants');
const Helpers = require('./helpers');

const BODY_WHY_BUTTON_TEXT = '💡 Навіщо заміри і цілі';

const BODY_WHY_TEXT =
  '💡 Навіщо заміри і цілі\n\n' +
  'Ці дані допомагають платформі (і тренеру, якщо він є) будувати плани, аналіз і прогресію під тебе — а не «середньостатистично».\n\n' +
  '📏 Поточні заміри\n' +
  '• AI-аналітика й підказки спираються на реальний стан тіла.\n' +
  '• Авто-підбір плану та навантаження стають точнішими.\n' +
  '• Після оновлень видно динаміку.\n\n' +
  '🎯 Бажані параметри\n' +
  '• Зрозуміло, куди ти йдеш (вага, талія, обсяги).\n' +
  '• Платформа оцінює реалістичність цілі та орієнтовні строки.\n' +
  '• Спільна ціль для тебе і тренера в плані й аналітиці.\n\n' +
  '🎯 Зони акценту та уникнення\n' +
  '• План і підбір вправ зміщують увагу на потрібні зони.\n' +
  '• Зони «не розвиваємо» зменшують акцент там, де це небажано.\n\n' +
  '🏃 Активність (бал 1–5)\n' +
  '• Враховує роботу, транспорт, кроки й активність поза залом.\n' +
  '• Впливає на щільність авто-плану та орієнтири по цілях.\n\n' +
  'Можна заповнювати не все одразу — навіть частина полів уже покращує плани й аналіз.';

/**
 * @param {string} chatId
 * @param {string} backCallback — повний callback_data кнопки «Назад»
 */
async function showBodyWhyHelp(chatId, backCallback) {
  const back = backCallback || CONSTANTS.CALLBACKS.BACK_TO_PROFILE;
  await Helpers.sendKeyboard(chatId, BODY_WHY_TEXT, [
    [{ text: CONSTANTS.EMOJI.BACK + ' Назад', callback_data: back }],
    [{ text: CONSTANTS.EMOJI.HOME + ' Головне меню', callback_data: CONSTANTS.CALLBACKS.BACK_TO_MAIN }]
  ]);
}

module.exports = {
  BODY_WHY_BUTTON_TEXT,
  BODY_WHY_TEXT,
  showBodyWhyHelp
};

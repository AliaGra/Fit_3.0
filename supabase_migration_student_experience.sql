-- Міграція: Досвід учня (Experience)
-- Встановлюється тренером вручну; статус обчислюється автоматично від дати встановлення.
-- Правила: 0–90 днів = 0–3 м-ців, 91–180 = 4–6 м-ців, 181–365 = 6–12 м-ців, 366+ (від реєстрації) = більше року.

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS experience_start_date timestamptz;

COMMENT ON COLUMN users.experience_start_date IS 'Дата, від якої рахується досвід учня (встановлює тренер). Від неї автоматично обчислюються дні досвіду для статусу 0–3 / 4–6 / 6–12 м-ців. Статус «більше року» — при досягненні 366+ днів від created_at (реєстрації).';

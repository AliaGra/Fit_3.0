-- 1. Довідник міст (без залежностей)
CREATE TABLE IF NOT EXISTS city_list (
  city_id    text,
  city_name  text,
  PRIMARY KEY (city_id)
);

-- 2. Користувачі
CREATE TABLE IF NOT EXISTS users (
  created_at   timestamptz,
  user_id      text NOT NULL,
  chat_id      text NOT NULL UNIQUE,
  first_name   text,
  last_name    text,
  city         text,
  role         text,
  gender       text,
  age          integer,
  goal         text,
  coach_id     text,
  birth_date   timestamptz,
  height       numeric,
  weight       numeric,
  waist        numeric,
  hip          numeric,          -- стегно (обхват стегна); НЕ ягодиці
  glutes       numeric,          -- ягодиці; для типу фігури / Navy / goal_hips
  arm          numeric,
  arm_flex     numeric,          -- біцепс у напрузі
  neck         numeric,
  wrist        numeric,          -- обовʼязкове для classifyBodyType
  shoulders    numeric,
  chest        numeric,
  body_fat_pct numeric,          -- ручний % жиру
  instagram    text,
  telegram_username text,
  calendar_id  text,
  experience_start_date timestamptz,
  ads_opt_in   boolean NOT NULL DEFAULT true,  -- новини/потенційні розсилки в місті
  PRIMARY KEY (chat_id)
);

-- 3. Бібліотека вправ (group_level1/2/3, name_ua, name_ru)
CREATE TABLE IF NOT EXISTS exercise_library (
  id              integer PRIMARY KEY,
  group_level1    text,
  group_level2    text,
  group_level3    text,
  name_ua         text,
  name_ru         text,
  equipment       text,
  active          text,
  focus_point     text,
  common_mistakes text,
  proper_feeling  text,
  static_holds    text,
  youtube_link    text,
  my_channel_link text,
  vid             text,  -- вид: базова, изоляция, стабилизация, растяжка
  difficulty      text   -- сложность: высокая, средняя, низкая
);

-- 4. Плани тренувань (coach_id → users)
CREATE TABLE IF NOT EXISTS training_plans (
  plan_id      text NOT NULL PRIMARY KEY,
  coach_id     text,
  plan_name    text,
  goal         text,
  level        text,
  description  text,
  is_active    text
);

-- 5. Вправи в планах (plan_id → training_plans)
CREATE TABLE IF NOT EXISTS training_plan_exercises (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id        text NOT NULL,
  day            integer,
  exercise_name  text,
  sets           integer,
  reps           integer,
  rest_sec       integer,
  notes          text
);

-- 6. Ціни (coach_id, student_id → users)
CREATE TABLE IF NOT EXISTS pricing (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coach_id               text NOT NULL,
  student_id             text,
  price_personal         numeric,
  price_split            numeric,
  price_trio             numeric,
  currency               text,
  updated_at             timestamptz,
  default_training_type  text
);

-- 7. Розклад тренувань (coach_id, student_id → users)
CREATE TABLE IF NOT EXISTS workout_schedule (
  id            text NOT NULL PRIMARY KEY,
  coach_id      text NOT NULL,
  student_id    text,
  date          timestamptz,
  time          text,
  status        text,
  updated_at    timestamptz,
  cal_event_id  text,
  price_charged numeric,
  currency      text,
  training_type text,
  reschedule_from_slot_id text NULL
);

-- 8. Історія замірів (chat_id → users)
-- Актуальні колонки = базові + міграції:
--   supabase_migration_measurements_neck_wrist.sql
--   supabase_migration_measurements_shoulders_chest_bodyfat.sql
--   supabase_migration_measurements_arm_flex.sql
CREATE TABLE IF NOT EXISTS measurements_history (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id       text NOT NULL,
  date          timestamptz,
  height        numeric,
  weight        numeric,
  waist         numeric,
  hip           numeric,          -- стегно (не плутати з glutes)
  glutes        numeric,          -- ягодиці
  arm           numeric,          -- біцепс розслаблено
  arm_flex      numeric,          -- біцепс напруга
  neck          numeric,
  wrist         numeric,
  shoulders     numeric,
  chest         numeric,
  body_fat_pct  numeric,
  source        text
);

-- 8b. Бажані параметри тіла
-- Міграції: supabase_migration_user_body_goals.sql, supabase_migration_user_body_goals_add_goal_arm.sql
CREATE TABLE IF NOT EXISTS user_body_goals (
  chat_id        text PRIMARY KEY,
  goal_weight    decimal(5,2),
  goal_waist     decimal(5,1),
  goal_hips      decimal(5,1),      -- бажані ЯГОДИЦІ (= users.glutes), НЕ стегно (hip)
  goal_shoulders decimal(5,1),
  goal_chest     decimal(5,1),
  goal_arm       decimal(5,1),      -- бажаний біцепс; окремо goal_neck / goal_wrist НЕМАЄ
  set_by_coach   text,
  goals_analysis jsonb,
  analysis_date  timestamptz,
  updated_at     timestamptz DEFAULT now()
);

-- 9. Записи тренувань (chat_id → users, exercise_id → exercise_library)
-- Колонка "set" в лапках: set — зарезервоване слово в PostgreSQL
CREATE TABLE IF NOT EXISTS bot_training_data (
  id_records  text NOT NULL,
  date        timestamptz,
  exercise_id integer,
  exercise    text,
  weight      numeric,
  reps        integer,
  "set"       integer,
  chat_id     text NOT NULL,
  PRIMARY KEY (id_records)
);

-- 10. Логи (опційно)
CREATE TABLE IF NOT EXISTS logs (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  timestamp timestamptz,
  context   text,
  message   text,
  stack     text
);

-- 10b. Журнал розсилок (тренер / заклад)
-- Міграції: supabase_migration_broadcast_ads.sql, supabase_migration_broadcast_potential_v11.sql
-- audience_type: own_all|own_active|own_sleeping|potential|pot_club|pot_city|pot_other
CREATE TABLE IF NOT EXISTS broadcast_log (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  sender_chat_id  text NOT NULL,
  sender_role     text NOT NULL,
  venue_id        text,            -- власник: заклад; pot_club: цільовий клуб
  audience_type   text NOT NULL,
  city            text,
  oblast          text,            -- для pot_other
  body            text NOT NULL,
  sent_count      integer NOT NULL DEFAULT 0,
  skipped_count   integer NOT NULL DEFAULT 0,
  failed_count    integer NOT NULL DEFAULT 0,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS broadcast_log_sender_created_idx
  ON broadcast_log (sender_chat_id, created_at DESC);
CREATE INDEX IF NOT EXISTS broadcast_log_venue_created_idx
  ON broadcast_log (venue_id, created_at DESC);
CREATE INDEX IF NOT EXISTS broadcast_log_audience_created_idx
  ON broadcast_log (audience_type, created_at DESC);

-- 10c. Дедуп нагадувань / вітань з ДН
-- Міграція: supabase_migration_birthday_reminders.sql
CREATE TABLE IF NOT EXISTS birthday_reminders_sent (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  recipient_chat_id text NOT NULL,
  subject_chat_id text NOT NULL,
  kind text NOT NULL,
  days_before integer NOT NULL,
  year integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS birthday_reminders_sent_uniq
  ON birthday_reminders_sent (recipient_chat_id, subject_chat_id, kind, days_before, year);

